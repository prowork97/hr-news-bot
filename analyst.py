_CITATION_RE = re.compile(r"\s*\[\d+\](?:\s*\[\d+\])*")
_META_RE = re.compile(r"(черновик|символов\s*\)|вот\s+(готовый\s+)?пост|draft)", re.I)


def _clean_output(text: str) -> str:
    """Приводит вывод Claude к чистому HTML-посту для Telegram."""
    if not text:
        return text
    text = text.strip()
    # снять обёртку блоков кода ```...```
    text = re.sub(r"^```[a-zA-Z]*\s*", "", text)
    text = re.sub(r"\s*```$", "", text).strip()
    # убрать мета-строки ИИ в начале («Черновик поста (~950 символов):» и т.п.)
    lines = text.split("\n")
    while lines and (_META_RE.search(lines[0]) or lines[0].strip() in ("", "---", "***")):
        lines.pop(0)
    text = "\n".join(lines)
    # markdown → HTML (Telegram понимает только HTML)
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)       # **жирный** → <b>
    text = re.sub(r"^#{1,6}\s*(.+)$", r"<b>\1</b>", text, flags=re.M)  # ## заголовок → <b>
    # убрать строки-разделители из трёх и более тире/звёзд
    text = re.sub(r"^[ \t]*[-–—*]{3,}[ \t]*$", "", text, flags=re.M)
    # убрать маркеры источников [1][2]
    text = _CITATION_RE.sub("", text)
    # схлопнуть лишние пустые строки
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def analyze_and_write(raw_data: dict, post_type: str) -> str:
    api_key = os.environ.get("ANTHROPIC_API_KEY", "")
    if not api_key:
        logger.error("ANTHROPIC_API_KEY не задан")
        return ""

    # не отдаём Claude внутренние служебные ключи (_sources, _hashtag и т.п.)
    if isinstance(raw_data, dict):
        clean_data = {k: v for k, v in raw_data.items() if not str(k).startswith("_")}
    else:
        clean_data = raw_data

    prompt_template = PROMPTS.get(post_type, PROMPTS["news"])
    user_prompt = prompt_template.format(
        raw_data=json.dumps(clean_data, ensure_ascii=False, indent=2)
    )

    try:
        client = anthropic.Anthropic(api_key=api_key)
        response = client.messages.create(
            model="claude-sonnet-4-6",
            max_tokens=2000,
            system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content": user_prompt}],
        )
        result = response.content[0].text.strip()
        result = _clean_output(result)  # чистим мета-текст, markdown, [N], разделители
        logger.info(f"Claude написал пост ({post_type}), {len(result)} символов")
        return result
    except Exception as e:
        logger.error(f"Claude API ошибка (post_type={post_type}): {e}")
        return ""
